#include <iostream>
using namespace std;

const int N = 10010, M = 100010;

int n, m;
char p[N], s[M];
// p：模式串（短串，要查找的子串，长度n）；s：文本串/主串（长串，被查找的大字符串，长度m）
// 约定：两个字符串全部从数组下标 1 开始存放，下标0闲置，规避边界判断麻烦
int ne[N]; 
// ne数组 = KMP的next数组；C++内置有next标识符，不能命名为next[]，所以简写ne[]
// ne[i]含义：模式串p前i个字符组成的子串，最长相等前后缀的长度

int main()
{
    cin >> n >> (p + 1) >> m >> (s + 1);    // cin p + 1 和 s + 1表示输入字符串
    
    // ========== 第一步：预处理模式串，构建ne(next)数组 ==========
    // i：遍历模式串，从第2位开始（ne[1]默认一定是0，单个字符没有前后缀）
    // j：当前最长相等前后缀的长度
    for (int i = 2, j = 0; i <= n; i++) // i 从 2 开始（next）next[1] 初始为0不用算
    {
        while (j && p[i] != p[j+1]) j = ne[j];
        if (p[i] == p[j+1]) j++;
        ne[i] = j;
    }


    // ========== 第二步：KMP主串匹配过程 ==========
    // i：主串s的遍历指针；j：模式串p的匹配指针
    for (int i = 1, j = 0; i <= m; i++) // Si要和 Pj+1进行比较
    {
        while (j && s[i] != p[j+1]) j = ne[j]; // 不匹配时，j如果为0，则说明退无可退，匹配失败，重新开始匹配。
        if (s[i] == p[j+1]) j++;
        if (j == n)
        {
            // 匹配成功
            printf("%d ", i - n + 1);
            j = ne[j];  // 最后匹配成功的话，
        }
    }


    return 0;
}
